from abc import ABCMeta, abstractmethod
import logging
import urllib.request as urllib_request
from urllib.parse import urlparse

from obspy.clients.base import RequestHookError


class HookRequest(metaclass=ABCMeta):
    """
    Stack-neutral, read-mostly view of an outgoing HTTP request.

    This is what a request hook actually receives - never the native
    :class:`urllib.request.Request` or :class:`requests.PreparedRequest`
    object directly, so that the same hook works against both.

    Header name capitalization is not normalized between the two backend
    implementations: urllib normalizes a name via ``str.capitalize()`` (so
    ``"X-Api-Key"`` becomes ``"X-api-key"``), while requests preserves it as
    given. Both are valid HTTP - header names are case-insensitive - but a
    hook that reads back its own header by name should compare names
    case-insensitively rather than assume a particular capitalization.
    """

    @property
    @abstractmethod
    def url(self):
        """The full URL the request is being sent to."""

    @property
    @abstractmethod
    def host(self):
        """The host (netloc) the request is being sent to."""

    @property
    @abstractmethod
    def scheme(self):
        """The URL scheme, e.g. ``"https"`` or ``"http"``."""

    @property
    @abstractmethod
    def method(self):
        """The HTTP method, e.g. ``"GET"`` or ``"POST"``."""

    @property
    @abstractmethod
    def headers(self):
        """
        A read-only mapping of the headers currently set on the request.

        Includes headers set by either :meth:`set_header` or
        :meth:`set_secret_header`, including by an earlier hook in a
        :func:`chain`, on both backends. The one caveat is name
        capitalization, not visibility - see the class docstring.

        Because this includes anything set via :meth:`set_secret_header`,
        a hook that logs, prints, or otherwise exports these values must
        redact the credential-bearing ones itself - see
        :attr:`LoggingHook.DEFAULT_REDACT` for the header names ObsPy's own
        included hook treats that way.
        """

    @abstractmethod
    def set_header(self, name, value):
        """
        Set a header on the outgoing request.

        Unlike :meth:`set_secret_header`, a header set this way is copied
        onto any redirect target the client may follow.

        :type name: str
        :param name: Header name.
        :type value: str
        :param value: Header value.
        """

    @abstractmethod
    def set_secret_header(self, name, value):
        """
        Set a header that must not be copied onto a cross-host redirect.

        This is the redirect-safe way to attach a credential (a bearer
        token, an API key, ...) to a request. Use it rather than
        :meth:`set_header` for anything sensitive.

        The two backends implement this differently:

        - On the urllib backend, the header is added with
          :meth:`Request.add_unredirected_header()
          <urllib.request.Request.add_unredirected_header>`. It is still
          sent with the request, but it is not part of the header dict
          ObsPy's redirect handler copies onto a redirect target, so it
          cannot follow a redirect to a different host.
        - On the requests backend, this is a plain header. It is still
          redirect-safe there because ``requests`` itself strips the
          ``Authorization`` header on a cross-host redirect
          (``Session.rebuild_auth()``).

        In other words: for the ``Authorization`` header specifically,
        ``set_secret_header`` is redirect-safe on both backends. For any
        other header name, only the urllib backend is guaranteed to drop it
        on a cross-host redirect.

        :type name: str
        :param name: Header name.
        :type value: str
        :param value: Header value.
        """


class _UrllibHookRequest(HookRequest):
    """
    :class:`HookRequest` view of a :class:`urllib.request.Request`.
    """
    def __init__(self, request):
        self._request = request

    @property
    def url(self):
        return self._request.full_url

    @property
    def host(self):
        return self._request.host

    @property
    def scheme(self):
        return self._request.type

    @property
    def method(self):
        return self._request.get_method()

    @property
    def headers(self):
        return dict(self._request.header_items())

    def set_header(self, name, value):
        self._request.add_header(name, value)

    def set_secret_header(self, name, value):
        self._request.add_unredirected_header(name, value)


class _RequestsHookRequest(HookRequest):
    """
    :class:`HookRequest` view of a :class:`requests.PreparedRequest`.
    """
    def __init__(self, request):
        self._request = request
        self._parsed = urlparse(request.url)

    @property
    def url(self):
        return self._request.url

    @property
    def host(self):
        return self._parsed.netloc

    @property
    def scheme(self):
        return self._parsed.scheme

    @property
    def method(self):
        return self._request.method

    @property
    def headers(self):
        return dict(self._request.headers)

    def set_header(self, name, value):
        self._request.headers[name] = value

    def set_secret_header(self, name, value):
        # requests has no unredirected-header concept; a plain header is
        # nonetheless redirect-safe for "Authorization" specifically, since
        # Session.rebuild_auth() strips that header on a cross-host
        # redirect. See the set_secret_header() docstring on HookRequest.
        self._request.headers[name] = value


def _call_hook(hook, hook_request, url_for_errors):
    """
    Invoke ``hook`` on ``hook_request``, wrapping any exception it raises.

    Shared by both backends so a broken hook fails the same way regardless
    of which client is using it. ``hook`` may itself be a :func:`chain` of
    hooks, each already run through this function - in that case the
    wrapping here is a no-op, since :exc:`RequestHookError` is re-raised
    rather than wrapped again, so the error keeps naming the hook that
    actually failed instead of the wrapping ``chain``.
    """
    try:
        hook(hook_request)
    except RequestHookError:
        raise
    except Exception as e:
        raise RequestHookError(
            "Request hook %r failed on '%s': %s" % (
                hook, url_for_errors, e)) from e


class RequestHookHandler(urllib_request.BaseHandler):
    """
    urllib handler that runs a request hook on every outgoing request.

    Add an instance of this to an :class:`~urllib.request.OpenerDirector`
    (e.g. via :func:`urllib.request.build_opener`) to have ``hook`` invoked
    on every request that opener sends, including ones generated by
    following a redirect.
    """
    # urllib's own do_request_() (which fills in the Host and
    # Content-Length headers, among others) runs at handler_order 500.
    # Running after it, at 900, means the hook always sees a fully
    # populated request - this is also why hooks may not rewrite the URL:
    # do_request_() would have already computed Host/Content-Length for the
    # *original* URL, and a hook running afterwards has no chance to fix
    # them up again.
    handler_order = 900

    def __init__(self, hook):
        self._hook = hook

    def http_request(self, req):
        _call_hook(self._hook, _UrllibHookRequest(req), req.full_url)
        return req

    https_request = http_request


class BearerTokenHook(object):
    """
    Request hook attaching an ``Authorization: Bearer <token>`` header.

    This is a convenience implementation of the request-hook protocol
    described in the module docstring, not a special case of it - it
    exists so that callers authenticating with a bearer token don't have
    to write their own hook calling :meth:`~HookRequest.set_secret_header`.

    Scoped per host, so that a single instance can be shared across a
    federated query touching several data centers, each with its own
    token - and so that a token for one data center is never sent to
    another.

    :type tokens: dict or callable
    :param tokens: Either a mapping of host (netloc) to the token to use
        for that host, or a single callable applied to every host.

        A mapping value is either a literal token string or a *token
        provider* - a callable ``f(request) -> token or None`` taking the
        :class:`HookRequest` and returning the token to use for this
        particular request, or ``None`` to leave it unauthenticated. A
        provider is what to use for a token that must be refreshed,
        fetched lazily, or resolved some other dynamic way; a literal
        string is the common static case. The two mix freely in one
        mapping. Only the provider mapped to the host the request is
        actually going to is ever invoked - a provider for one data
        center is never consulted for a request to another, let alone its
        token attached.

        Passing a single callable ``f(request) -> token or None`` in
        place of the whole mapping applies it to every host, with no
        allowlist. Use that form when the hosts are not known up front or
        need pattern matching; use the mapping form - whose keys double
        as the allowlist - otherwise.

        A callable in either position is a *token resolver*, not a
        request hook itself: it returns a token string (or ``None``)
        rather than mutating the request. ``BearerTokenHook`` is the
        hook; it is what calls :meth:`~HookRequest.set_secret_header`
        with the token the resolver returns, together with the header
        name, the ``Bearer `` prefix, the ``require_https`` guard, and
        the fail-open behaviour described below. Such a callable may be
        invoked concurrently from several threads (see the module
        docstring) and must handle that itself. It is consulted afresh
        on every request that could carry its token - never cached
        between them, which is what makes refresh work - and is not
        consulted at all for a request suppressed by ``require_https``,
        so a plain-http request never triggers a token refresh. If it
        raises, the exception is wrapped in
        :exc:`~obspy.clients.base.RequestHookError` naming this hook and
        the URL, never swallowed. See the module docstring for a worked
        example delegating to an external authentication SDK.

        Mapping keys are exact netlocs, matched case-insensitively - i.e.
        including an explicit port if the URL carries one, such as
        ``"example.com:8080"`` - since host names are not case-sensitive
        but this lookup would otherwise be an exact string match. There
        is no wildcard or glob matching on keys; use the single-callable
        form if you need that.

        A host that is not present in the mapping (or for which a
        callable returns ``None``) is left alone - the request goes out
        unauthenticated rather than raising. This "fail open" behaviour is
        deliberate: most FDSN data centers do not require authentication,
        and a federated query should not break against those just because
        this hook does not have a token for them.
    :type require_https: bool
    :param require_https: If ``True`` (the default), never attach the
        token to a plain HTTP request, to avoid sending it in the clear.
    """
    def __init__(self, tokens, require_https=True):
        if callable(tokens):
            self._resolve = tokens
            # Only a name, never the object's repr - a callable holding a
            # token could put it in its own repr, and this ends up in
            # error messages and tracebacks. See __repr__.
            self._description = getattr(
                tokens, "__name__", type(tokens).__name__)
        else:
            _tokens = {host.lower(): token for host, token in tokens.items()}
            self._description = "hosts=%r" % (sorted(_tokens),)

            def _resolve(request):
                # A mapping value is either a literal token or a token
                # provider with the same signature as the whole-mapping
                # resolver form. Only the provider mapped to the host the
                # request is actually going to is ever invoked.
                token = _tokens.get(request.host.lower())
                if callable(token):
                    token = token(request)
                return token

            self._resolve = _resolve
        self._require_https = require_https

    def __repr__(self):
        return "%s(%s)" % (type(self).__name__, self._description)

    def __call__(self, request):
        if self._require_https and request.scheme != "https":
            return
        token = self._resolve(request)
        if token is None:
            return
        request.set_secret_header("Authorization", "Bearer " + token)


class LoggingHook(object):
    """
    Request hook that logs every outgoing request. Never mutates a request.

    Like :class:`BearerTokenHook`, this is a convenience implementation of
    the request-hook protocol, not a special case of it - logging every
    outgoing request is common enough to be worth a ready-made hook for,
    but nothing here couldn't be written as a two-line function of your
    own.

    Useful on its own, or composed with :func:`chain` alongside an
    authenticating hook, to get a record of every URL and host a federated
    download actually touched.

    With ``headers=True``, also logs the request's headers - including any
    added by an earlier hook in a :func:`chain`, such as an
    ``Authorization`` header attached by :class:`BearerTokenHook` - which is
    the way to answer "did my auth hook actually attach a token?" without
    writing a throwaway hook of your own. Because :attr:`HookRequest.headers`
    deliberately includes headers set via
    :meth:`~HookRequest.set_secret_header` (see that method's docstring),
    values considered credentials are redacted by default; see ``redact``
    below. Only headers set by a hook *earlier* in the chain are visible, so
    ``chain(LoggingHook(headers=True), BearerTokenHook(...))`` logs the
    request before the token is attached, while the reverse order logs it
    (redacted) afterwards.

    :type logger: :class:`logging.Logger`
    :param logger: Logger to use. Defaults to a logger named
        ``"obspy.clients.hooks"``.
    :type level: int
    :param level: Logging level to log requests at. Defaults to
        :data:`logging.DEBUG`.
    :type headers: bool
    :param headers: If ``True``, also log the request's headers, one per
        line, sorted by name. Defaults to ``False``.
    :type redact: iterable of str or None
    :param redact: Header names (matched case-insensitively) whose values
        are replaced with ``"<redacted>"`` rather than logged as-is. Only
        relevant when ``headers=True``. Defaults to
        :attr:`DEFAULT_REDACT`; pass ``()`` to log every value verbatim -
        not recommended for anything hitting a real data center.
    """
    #: Header names (case-insensitive) redacted by default when
    #: ``headers=True`` - the common carriers of a credential.
    DEFAULT_REDACT = ("authorization", "proxy-authorization", "cookie",
                      "set-cookie", "x-api-key")

    def __init__(self, logger=None, level=logging.DEBUG, headers=False,
                 redact=None):
        self._logger = logger or logging.getLogger("obspy.clients.hooks")
        self._level = level
        self._headers = headers
        self._redact = frozenset(
            name.lower() for name in
            (self.DEFAULT_REDACT if redact is None else redact))

    def __call__(self, request):
        if not self._headers:
            self._logger.log(
                self._level, "%s %s", request.method, request.url)
            return
        # Guard explicitly rather than relying on the logger to no-op on a
        # disabled level - building the header block is not free, and
        # nothing here should touch header values at all when nothing is
        # going to be logged.
        if not self._logger.isEnabledFor(self._level):
            return
        lines = ["%s %s" % (request.method, request.url)]
        for name, value in sorted(request.headers.items()):
            if name.lower() in self._redact:
                value = "<redacted>"
            lines.append("    %s: %s" % (name, value))
        self._logger.log(self._level, "\n".join(lines))


def chain(*hooks):
    """
    Compose several request hooks into a single one.

    Clients accept a single ``request_hook``; use this to combine several,
    e.g. an authenticating hook and a logging hook. Hooks run in the order
    given, each seeing the request as left by the previous one.

    An included hook and a plain function hook compose the same way - the
    ``chain`` below combines both:

    >>> from obspy.clients.hooks import BearerTokenHook, chain
    >>> def add_project_header(request):
    ...     request.set_header("X-Project-Id", "my-project")
    >>> hook = chain(
    ...     BearerTokenHook({'service.earthscope.org': 'token'}),
    ...     add_project_header,
    ... )
    """
    def _chained(request):
        for hook in hooks:
            # Route each hook through _call_hook individually, rather than
            # just calling it directly and letting a raise propagate up to
            # be wrapped by the *caller's* _call_hook - that would report
            # the error as coming from this "hook" (i.e. _chained itself)
            # rather than from whichever hook in the chain actually failed.
            _call_hook(hook, request, request.url)
    return _chained


